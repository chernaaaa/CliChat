package ru.hse.clichat.network;

/**
 * Интерфейс для узла P2P чата (сервера или клиента).
 * Предоставляет общие операции для отправки сообщений и управления соединением.
 */
public interface GrpcChatNode {
    /**
     * Отправляет текстовое сообщение собеседнику.
     * Пустые или null сообщения игнорируются.
     *
     * @param text текст сообщения
     */
    void sendMessage(String text);
    
    /**
     * Закрывает соединение и освобождает все ресурсы.
     * Метод может быть вызван многократно безопасно.
     */
    void disconnect();
}
